// Variables pour le carrousel
var indexPhotoActuelle = 0;
var photosActuelles = [];

// Fonction pour ouvrir le pop-up
function ouvrirPopup(projet) {
    document.querySelector("#popup-titre").innerHTML = projet.titre;
    document.querySelector("#popup-description").innerHTML = projet.description;
    photosActuelles = projet.photos;
    indexPhotoActuelle = 0;
    document.querySelector("#carrousel-image").src = photosActuelles[0];
    document.querySelector("#popup").style.display = "flex";
}

// Fonction pour fermer le pop-up
function fermerPopup() {
    document.querySelector("#popup").style.display = "none";
}

// Fonction principale qui génère les blocs projets
function ajouteProjets(data) {
    var nbProjets = 0;

    data.forEach(function(p) {
        nbProjets = nbProjets + 1;
        console.log('Projet numero ' + nbProjets + ' : ' + p.titre);

        // Création du bloc HTML
        var blocProjet = document.createElement("li");
        blocProjet.innerHTML = '<h2>' + p.titre + '</h2>'
            + '<p class="indice">↓ Cliquer sur le titre pour en savoir plus</p>'
            + '<p><em>' + p.type + '</em></p>'
            + '<img src="' + p.photos[0] + '" alt="' + p.titre + '" class="image-projet">'
            + '<p>' + p.description + '</p>';

        // Rendre l'image cliquable pour le pop-up
        var img = blocProjet.querySelector(".image-projet");
        img.style.cursor = "pointer";
        img.addEventListener("click", function() {
            ouvrirPopup(p);
        });

        // Clic sur le titre pour afficher/masquer la description
        var titre = blocProjet.querySelector("h2");
        var description = blocProjet.querySelector("p:last-child");
        description.style.display = "none";
        titre.style.cursor = "pointer";
        titre.addEventListener("click", function() {
            if (description.style.display == "none") {
                description.style.display = "block";
            } else {
                description.style.display = "none";
            }
        });

        // Ajout du bloc dans la page
        document.querySelector("#liste-projets").append(blocProjet);
    });
}

// Bouton fermer le pop-up
document.querySelector("#popup-fermer").addEventListener("click", function() {
    fermerPopup();
});

// Fermer en cliquant en dehors du contenu
document.querySelector("#popup").addEventListener("click", function(event) {
    if (event.target == document.querySelector("#popup")) {
        fermerPopup();
    }
});

// Bouton photo suivante
document.querySelector("#btn-suivant").addEventListener("click", function() {
    indexPhotoActuelle = indexPhotoActuelle + 1;
    if (indexPhotoActuelle >= photosActuelles.length) {
        indexPhotoActuelle = 0;
    }
    document.querySelector("#carrousel-image").src = photosActuelles[indexPhotoActuelle];
});

// Bouton photo précédente
document.querySelector("#btn-precedent").addEventListener("click", function() {
    indexPhotoActuelle = indexPhotoActuelle - 1;
    if (indexPhotoActuelle < 0) {
        indexPhotoActuelle = photosActuelles.length - 1;
    }
    document.querySelector("#carrousel-image").src = photosActuelles[indexPhotoActuelle];
});

// Appel de la fonction principale
ajouteProjets(dataProjets);

